"""
app/api/jobs.py
---------------
FastAPI router handling all job-level endpoints.

Phase 5: POST /api/jobs/  — create a bulk generation job
Phase 10: GET  /api/jobs/{job_id}                — job status / progress
Phase 11: GET  /api/jobs/{job_id}/certificates   — list all certificates

Why APIRouter and not direct @app decorators?
----------------------------------------------
`APIRouter` keeps related endpoints grouped in their own module.  The main
`app.main` just mounts the router — it doesn't need to know the
implementation details.  This makes the codebase scale cleanly: adding a new
group of endpoints is one file + one `app.include_router()` call.
"""

import logging
import uuid

from fastapi import APIRouter, BackgroundTasks, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.models.certificate import Certificate, CertificateStatus
from app.models.job import GenerationJob, JobStatus
from app.schemas.job import (
    CreateJobRequest,
    CreateJobResponse,
    JobCertificatesResponse,
    JobStatusResponse,
)
from app.workers.certificate_worker import process_job

logger = logging.getLogger(__name__)

router = APIRouter(
    prefix="/api/jobs",
    tags=["Jobs"],
)


# ─────────────────────────────────────────────────────────────────────────────
# POST /api/jobs/  —  Create a bulk generation job
# ─────────────────────────────────────────────────────────────────────────────


@router.post(
    "/",
    status_code=status.HTTP_202_ACCEPTED,
    response_model=CreateJobResponse,
    summary="Create a bulk certificate generation job",
    response_description=(
        "Job accepted.  Generation runs in the background. "
        "Poll GET /api/jobs/{job_id} for progress."
    ),
)
def create_job(
    request: CreateJobRequest,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db),
) -> CreateJobResponse:
    """
    Accept a certificate generation request and immediately return HTTP 202.

    ### What happens synchronously (before the response is sent)
    1. Pydantic validates the request body (handled automatically by FastAPI).
    2. A `GenerationJob` row is inserted with status `PENDING`.
    3. One `Certificate` row per recipient is inserted with status `PENDING`.
    4. The entire insert (job + all certificates) is committed atomically.
    5. The background worker is registered with `BackgroundTasks`.

    ### What happens asynchronously (after the response is sent)
    6. FastAPI sends the HTTP 202 response to the client.
    7. The background worker runs `process_job(job_id)` in a thread-pool
       thread, generating one PDF per certificate sequentially.

    ### Why HTTP 202 and not 201?
    - 201 Created means the resource is fully created and ready.
    - 202 Accepted means the request is valid and queued, but the work
      is not yet complete.  Clients must poll for completion.

    ### Transaction boundary
    ```
    BEGIN
      INSERT INTO generation_jobs  (1 row)
      INSERT INTO certificates     (N rows)
    COMMIT
    → register BackgroundTask
    ```
    The background task is added ONLY after a successful commit.
    If the commit fails, the task is never registered — no orphaned worker.
    """
    logger.info(
        "Job creation request received: %d recipient(s), title='%s'",
        len(request.recipients),
        request.certificate_title,
    )

    # ── 1. Build the job record ─────────────────────────────────────────────────
    # The UUID is generated by `default=uuid.uuid4` on the model, so `job.id`
    # is available immediately — before the INSERT — which lets us reference
    # it when building Certificate rows and constructing the response.
    job = GenerationJob(
        status=JobStatus.PENDING,
        total_count=len(request.recipients),
        certificate_title=request.certificate_title,
        course_name=request.course_name,
        organization=request.organization,
        issue_date=request.issue_date,
    )
    db.add(job)

    # ── 2. Build certificate records ────────────────────────────────────────────
    # We flush the job first to ensure the job.id FK is valid in PostgreSQL.
    # `flush()` sends the SQL to the DB within the open transaction but does
    # NOT commit — the job row is only visible to this session until commit.
    db.flush()

    certificates: list[Certificate] = []
    for recipient in request.recipients:
        cert = Certificate(
            job_id=job.id,
            recipient_name=recipient.name,
            recipient_email=recipient.email,
            status=CertificateStatus.PENDING,
        )
        db.add(cert)
        certificates.append(cert)

    # ── 3. Commit atomically ────────────────────────────────────────────────────
    # If the commit raises, SQLAlchemy automatically rolls back the transaction
    # (because the Session is closed in get_db's `finally` block).
    # No partial state is written to the database.
    try:
        db.commit()
    except Exception as exc:
        logger.error(
            "Failed to persist job and certificates for request: %s",
            exc,
            exc_info=True,
        )
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={
                "error": {
                    "code": "DATABASE_ERROR",
                    "message": "Failed to create the generation job. Please try again.",
                }
            },
        ) from exc

    logger.info(
        "Job %s created with %d certificates — dispatching background worker",
        job.id,
        len(certificates),
    )

    # ── 4. Register background task ─────────────────────────────────────────────
    # `add_task` does NOT start the task here.  FastAPI queues it and runs it
    # in a thread-pool thread after the HTTP response is sent.
    #
    # CRITICAL: We pass job.id (a UUID value) — NOT the ORM object.
    # The ORM object is bound to `db` (the request session) which will be
    # closed by the time the background task runs.  Passing the ID lets the
    # worker open its own session and reload data safely.
    background_tasks.add_task(process_job, job_id=job.id)

    # ── 5. Build and return the response ───────────────────────────────────────
    # `model_validate` reads from the ORM object's attributes.
    return CreateJobResponse.model_validate(job)


# ─────────────────────────────────────────────────────────────────────────────
# GET /api/jobs/{job_id}  —  Get job progress and status
# ─────────────────────────────────────────────────────────────────────────────


@router.get(
    "/{job_id}",
    response_model=JobStatusResponse,
    summary="Get job progress",
    response_description="Returns the current processing status and counts.",
)
def get_job_status(
    job_id: uuid.UUID,
    db: Session = Depends(get_db),
) -> JobStatusResponse:
    """
    Retrieve the current status of a generation job.

    This endpoint is incredibly fast (O(1)) because we stored `completed_count`
    and `failed_count` directly on the `GenerationJob` row. It does not need
    to join the `certificates` table or run `COUNT(*)` aggregates.

    The Pydantic response schema automatically computes `pending_count` and
    `progress` (percentage) on the fly.
    """
    job = db.query(GenerationJob).filter(GenerationJob.id == job_id).first()

    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={
                "error": {
                    "code": "JOB_NOT_FOUND",
                    "message": f"Job with ID {job_id} does not exist.",
                }
            },
        )

    return JobStatusResponse.model_validate(job)


# ─────────────────────────────────────────────────────────────────────────────
# GET /api/jobs/{job_id}/certificates  —  List all certificates for a job
# ─────────────────────────────────────────────────────────────────────────────


@router.get(
    "/{job_id}/certificates",
    response_model=JobCertificatesResponse,
    summary="List job certificates",
    response_description="Returns all certificate records associated with the job.",
)
def get_job_certificates(
    job_id: uuid.UUID,
    db: Session = Depends(get_db),
) -> dict:
    """
    Retrieve all individual certificates for a given job.

    This query returns the full list of certificates. For COMPLETED
    certificates, a download URL is automatically generated and included.

    Note: We return a dictionary that matches the JobCertificatesResponse
    schema, letting FastAPI/Pydantic handle the final validation and serialization.
    """
    job = db.query(GenerationJob).filter(GenerationJob.id == job_id).first()

    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={
                "error": {
                    "code": "JOB_NOT_FOUND",
                    "message": f"Job with ID {job_id} does not exist.",
                }
            },
        )

    # We fetch the certificates explicitly instead of relying on the ORM
    # lazy-loaded relationship. This is generally safer in APIs to prevent
    # accidental N+1 queries.
    certificates = (
        db.query(Certificate)
        .filter(Certificate.job_id == job_id)
        # Order by creation so the list is stable
        .order_by(Certificate.created_at.asc())
        .all()
    )

    # We construct the response payload manually so we can inject the
    # `download_url` for completed certificates. This keeps the ORM model
    # completely ignorant of HTTP routing.
    cert_responses = []
    for cert in certificates:
        cert_dict = {
            "id": cert.id,
            "recipient_name": cert.recipient_name,
            "recipient_email": cert.recipient_email,
            "status": cert.status,
            "error_message": cert.error_message,
            "created_at": cert.created_at,
            "updated_at": cert.updated_at,
            "completed_at": cert.completed_at,
            # Only provide a download URL if the PDF was successfully generated
            "download_url": (
                f"/api/certificates/{cert.id}/download"
                if cert.status == CertificateStatus.COMPLETED
                else None
            ),
        }
        cert_responses.append(cert_dict)

    return {
        "job_id": job.id,
        "status": job.status,
        "total_count": job.total_count,
        "certificates": cert_responses,
    }
